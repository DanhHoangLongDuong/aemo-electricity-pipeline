CREATE TABLE IF NOT EXISTS `aemo-pipeline.raw.price` (
    SETTLEMENTDATE DATETIME NOT NULL,
    REGIONID STRING NOT NULL,
    RUNNO INT64 NOT NULL,
    INTERVENTION INT64 NOT NULL,
    RRP NUMERIC,
    PRICE_STATUS STRING,
    LASTCHANGED DATETIME,
    source_file STRING NOT NULL
)
PARTITION BY DATETIME_TRUNC(SETTLEMENTDATE, DAY);

